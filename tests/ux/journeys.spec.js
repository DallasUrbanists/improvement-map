import { test, expect, draftKey, draft, photo } from './fixture.js';
import { audit, assertDraft } from './audit.js';

test('browse, search, history, photos, settings and theme', async ({ page }, info) => {
  const check = audit(page, info);
  await page.goto('/?view=map');
  await expect(page.locator('.map-zoom-ui')).toBeVisible();
  const toolbarButtons = page.locator('.map-toolbar > button');
  for (const button of await toolbarButtons.all()) {
    const box = await button.boundingBox();
    expect.soft(box.width, 'toolbar touch width').toBeGreaterThanOrEqual(44);
    expect.soft(box.height, 'toolbar touch height').toBeGreaterThanOrEqual(44);
  }
  const toolbarBox = await page.locator('.map-toolbar').boundingBox();
  expect.soft(toolbarBox.x).toBeGreaterThanOrEqual(0);
  expect.soft(toolbarBox.x + toolbarBox.width).toBeLessThanOrEqual(page.viewportSize().width);
  await check('browse-map');
  await page.getByRole('button', { name: 'Browse', exact: true }).click();
  await expect(page.getByText('Suggestion 1', { exact: true })).toBeVisible();
  await check('browse-list');
  const scroll = page.locator('.map-tray-content');
  await scroll.evaluate(el => { el.scrollTop = 200; });
  await expect.poll(() => scroll.evaluate(el => el.scrollTop)).toBeGreaterThan(0);
  await scroll.evaluate(el => { el.scrollTop = 0; });
  const card = page.locator('[data-suggestion-id="1"]');
  await card.focus(); await card.press('Enter');
  await expect(page.getByRole('region', { name: 'Submission details', exact: true })).toHaveAttribute('aria-busy', 'false');
  await check('details');
  await page.locator('summary').filter({ hasText: 'Photos (2)' }).click();
  await page.getByRole('button', { name: 'Open photo 1: Crossing photo 1' }).click();
  await expect(page.getByAltText('Full size')).toBeVisible();
  await check('photo-preview');
  await page.getByRole('button', { name: 'Close photo preview' }).click();
  await page.getByRole('button', { name: 'Open photo 2: Crossing photo 2' }).click();
  await check('photo-second');
  await page.getByRole('button', { name: 'Close photo preview' }).click();
  await page.goBack();
  await expect(card).toBeFocused();
  await page.goForward();
  await expect(page.getByRole('region', { name: 'Submission details', exact: true })).toHaveAttribute('aria-busy', 'false');
  await page.goBack();
  await page.getByRole('button', { name: 'Search address or neighborhood', exact: true }).click();
  await page.getByRole('textbox', { name: 'Search address or neighborhood' }).fill('Main');
  await expect(page.getByRole('button', { name: 'Searched address, Dallas, TX' })).toBeVisible();
  await check('search-results');
  await page.getByRole('button', { name: 'Searched address, Dallas, TX' }).click();
  await page.getByRole('button', { name: 'Menu', exact: true }).click();
  await check('settings-menu');
  await page.getByRole('menuitem', { name: 'Marker settings', exact: true }).click();
  await expect(page.getByRole('dialog', { name: 'Marker settings' })).toBeVisible();
  await check('marker-settings');
  const size = page.viewportSize();
  await page.setViewportSize({ width: size.height, height: size.width });
  const settings = page.getByRole('dialog', { name: 'Marker settings', exact: true });
  const threshold = page.getByRole('slider', { name: 'Marker threshold zoom level' });
  const settingsBox = await settings.boundingBox();
  const thresholdBox = await threshold.boundingBox();
  expect.soft(thresholdBox.y + thresholdBox.height, 'first settings control fits without scrolling').toBeLessThan(settingsBox.y + settingsBox.height);
  await settings.evaluate(el => { el.scrollTop = el.scrollHeight; });
  await expect(page.getByRole('button', { name: 'Close marker settings', exact: true })).toBeInViewport();
  await settings.evaluate(el => { el.scrollTop = 0; });
  await check('marker-settings-rotated');
  await page.getByRole('button', { name: 'Close marker settings', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Menu', exact: true })).toBeFocused();
  await page.setViewportSize(size);
  await page.getByRole('button', { name: 'Menu', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Rail settings', exact: true }).click();
  await check('rail-settings');
  await page.getByRole('button', { name: 'Close rail settings', exact: true }).click();
  await page.getByRole('button', { name: 'Menu', exact: true }).click();
  const theme = info.project.use.colorScheme === 'dark' ? 'Light' : 'Dark';
  await page.getByRole('menuitemradio', { name: `${theme} theme` }).click();
  await expect(page.locator('html')).toHaveClass(new RegExp(theme.toLowerCase()));
  await check('theme-switched');
});

test('submission edits, draft resume, validation, upload failure and retry', async ({ page }, info) => {
  const check = audit(page, info);
  await page.goto('/submit');
  await page.getByTestId('pin-and-continue').waitFor();
  await check('submit-locate');
  await page.getByTestId('pin-and-continue').click();
  await check('submit-photos-empty');
  await page.locator('input[type=file]').first().setInputFiles({ name: 'crossing.svg', mimeType: 'image/svg+xml', buffer: Buffer.from(photo.split(',')[1], 'base64') });
  await expect(page.getByRole('textbox', { name: 'Caption for photo 1' })).toBeVisible();
  await page.getByRole('textbox', { name: 'Caption for photo 1' }).fill('Busy crossing');
  await check('submit-photo-added');
  await page.getByRole('button', { name: 'Remove photo 1', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Skip photos', exact: true })).toBeVisible();
  await page.locator('input[type=file]').first().setInputFiles({ name: 'crossing.svg', mimeType: 'image/svg+xml', buffer: Buffer.from(photo.split(',')[1], 'base64') });
  await page.getByRole('button', { name: 'Next', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Describe your idea' })).toBeVisible();
  await page.locator('textarea').first().fill('short');
  await expect(page.getByRole('button', { name: 'Next', exact: true })).toBeDisabled();
  await check('description-invalid');
  const details = 'Please improve pedestrian safety at this busy crossing. '.repeat(30);
  await page.locator('textarea').first().fill(details);
  await check('description-long');
  await page.getByRole('button', { name: 'Next', exact: true }).click();
  await check('submit-review');
  await page.getByRole('button', { name: 'Edit description' }).click();
  await expect(page.locator('textarea').first()).toHaveValue(details);
  await page.getByRole('button', { name: 'Next', exact: true }).click();
  await page.reload();
  await expect(page.getByRole('region', { name: 'Review submission' })).toBeVisible();
  await assertDraft(page, draftKey, { step: 4, details });
  await check('draft-restored');
  await page.getByRole('button', { name: 'Close Review submission' }).click();
  await page.getByRole('button', { name: 'Submit', exact: true }).click();
  await expect(page.getByTestId('pin-and-continue')).toBeVisible();
  await assertDraft(page, draftKey, { step: 1, details });
  await check('submit-reopened-at-locate');
  await page.getByTestId('pin-and-continue').click();
  await page.getByTestId('photo-navigation-segment').getByRole('button', { name: 'Next', exact: true }).click();
  await page.getByTestId('step-three-navigation').getByRole('button', { name: 'Next', exact: true }).click();
  await page.locator('#input-author-name').fill('');
  await page.locator('#input-author-email').fill('invalid');
  const submit = page.getByTestId('step-four-navigation').getByRole('button', { name: 'Submit', exact: true });
  await submit.click();
  expect(await page.evaluate(() => window.__ux.submits)).toBe(0);
  await check('review-invalid');
  await page.locator('#input-author-name').fill(draft.author.name);
  await page.locator('#input-author-email').fill(draft.author.email);
  await page.evaluate(() => { window.__ux.uploadFail = true; window.__ux.hold = true; });
  await submit.click();
  await check('submission-loading');
  await page.evaluate(() => { window.__ux.hold = false; });
  await expect(page.getByRole('heading', { name: 'Submission Failed' })).toBeVisible();
  await check('submission-error');
  await page.evaluate(() => { window.__ux.uploadFail = false; window.__ux.delay = 0; });
  await page.getByRole('button', { name: 'Retry submission', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Submission complete!' })).toBeVisible();
  await check('submission-success');
});

test('empty, denied location, unavailable detail and enlarged text', async ({ page }, info) => {
  const check = audit(page, info);
  await page.addInitScript(() => { window.__ux.empty = true; });
  await page.goto('/?view=list');
  await expect(page.getByRole('heading', { name: 'No suggestions found' })).toBeVisible();
  await check('browse-empty');
  await page.getByRole('button', { name: 'Sort by distance' }).click();
  await check('location-denied');
  await page.addStyleTag({ content: 'html { font-size: 200% !important; }' });
  await check('enlarged-text');
  await page.goto('/suggestion/missing');
  await expect(page.getByRole('heading', { name: 'Suggestion Not Found' })).toBeVisible();
  await check('detail-error');
});
