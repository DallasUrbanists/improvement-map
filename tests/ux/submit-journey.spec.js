import { test, expect, draftKey, draft, photo } from './fixture.js';
import { audit, assertDraft } from './audit.js';

test('submission edits, draft resume, validation, upload failure and retry', async ({ page }, info) => {
  const check = audit(page, info);
  await page.goto('/submit');
  await page.getByTestId('pin-and-continue').waitFor();
  await expect(page.getByText('Set pin and continue', { exact: true })).toBeVisible();
  await check('submit-locate');
  await page.getByTestId('pin-and-continue').click();
  await check('submit-photos-empty');
  await page.locator('input[type=file]').first().setInputFiles({ name: 'crossing.svg', mimeType: 'image/svg+xml', buffer: Buffer.from(photo.split(',')[1], 'base64') });
  await page.locator('input[type=file]').first().setInputFiles({ name: 'second.svg', mimeType: 'image/svg+xml', buffer: Buffer.from(photo.split(',')[1], 'base64') });
  await expect(page.getByText('2 / 2', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Previous photo', exact: true }).click();
  await expect(page.getByText('1 / 2', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Next photo', exact: true }).click();
  await expect(page.getByText('2 / 2', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Remove photo 2', exact: true }).click();
  await expect(page.getByRole('textbox', { name: 'Caption for photo 1' })).toBeVisible();
  await page.getByRole('textbox', { name: 'Caption for photo 1' }).fill('Busy crossing');
  await check('submit-photo-added');
  await page.getByRole('button', { name: 'Remove photo 1', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Skip photos', exact: true })).toBeVisible();
  await page.locator('input[type=file]').first().setInputFiles({ name: 'crossing.svg', mimeType: 'image/svg+xml', buffer: Buffer.from(photo.split(',')[1], 'base64') });
  await page.getByRole('dialog', { name: 'Attach photos', exact: true }).locator('.floating-modal__footer').getByRole('button', { name: 'Next', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Describe your idea' })).toBeVisible();
  await page.locator('textarea').first().fill('short');
  await expect(page.getByTestId('step-three-navigation').getByRole('button', { name: 'Next', exact: true })).toBeDisabled();
  await check('description-invalid');
  const details = 'Please improve pedestrian safety at this busy crossing. '.repeat(30);
  await page.locator('textarea').first().fill(details);
  await check('description-long');
  await page.getByTestId('step-three-navigation').getByRole('button', { name: 'Next', exact: true }).click();
  await check('submit-review');
  await page.getByRole('button', { name: 'Edit description' }).click();
  await expect(page.locator('textarea').first()).toHaveValue(details);
  await page.getByTestId('step-three-navigation').getByRole('button', { name: 'Next', exact: true }).click();
  await page.reload();
  await expect(page.getByRole('region', { name: 'Review submission' })).toBeVisible();
  await assertDraft(page, draftKey, { step: 4, details });
  await check('draft-restored');
  await page.getByRole('button', { name: 'Close Review submission' }).click();
  await page.getByRole('button', { name: 'New', exact: true }).click();
  await expect(page.getByTestId('pin-and-continue')).toBeVisible();
  await assertDraft(page, draftKey, { step: 1, details });
  await check('submit-reopened-at-locate');
  await page.getByTestId('pin-and-continue').click();
  await page.getByRole('dialog', { name: 'Attach photos', exact: true }).locator('.floating-modal__footer').getByRole('button', { name: 'Next', exact: true }).click();
  await page.getByTestId('step-three-navigation').getByRole('button', { name: 'Next', exact: true }).click();
  await page.locator('#input-author-name').fill('');
  await page.locator('#input-author-email').fill('invalid');
  const submit = page.getByTestId('step-four-navigation').getByRole('button', { name: 'Submit', exact: true });
  await submit.click();
  expect(await page.evaluate(() => window.__ux.submits)).toBe(0);
  await check('review-invalid');
  await page.locator('#input-author-name').fill(draft.author.name);
  await page.locator('#input-author-email').fill(draft.author.email);
  await page.evaluate(() => { window.__ux.uploadFail = true; window.__ux.hold = true; });
  await submit.click();
  await check('submission-loading');
  await page.evaluate(() => { window.__ux.hold = false; });
  await expect(page.getByRole('heading', { name: 'Submission Failed' })).toBeVisible();
  await check('submission-error');
  await page.evaluate(() => { window.__ux.uploadFail = false; window.__ux.delay = 0; });
  await page.getByRole('button', { name: 'Retry submission', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Submission complete!' })).toBeVisible();
  await check('submission-success');
});
