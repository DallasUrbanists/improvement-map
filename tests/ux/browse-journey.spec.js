import { test, expect, draftKey, draft, photo } from './fixture.js';
import { audit, assertDraft } from './audit.js';

test('browse, search, history, photos, settings and theme', async ({ page }, info) => {
  const check = audit(page, info);
  await page.goto('/?view=map');
  await expect(page.locator('.map-search-panel')).toBeVisible();
  await expect(page.getByRole('button', { name: 'Zoom in' })).toHaveCount(0);
  const toolbarButtons = page.locator('.map-list-fab');
  for (const button of await toolbarButtons.all()) {
    const box = await button.boundingBox();
    expect.soft(box.width, 'toolbar touch width').toBeGreaterThanOrEqual(44);
    expect.soft(box.height, 'toolbar touch height').toBeGreaterThanOrEqual(44);
  }
  const toolbarBox = await page.locator('.map-list-fab').boundingBox();
  expect.soft(toolbarBox.x).toBeGreaterThanOrEqual(0);
  expect.soft(toolbarBox.x + toolbarBox.width).toBeLessThanOrEqual(page.viewportSize().width);
  await check('browse-map');
  await page.getByRole('button', { name: 'List', exact: true }).click();
  await expect(page.getByText('Suggestion 1', { exact: true })).toBeVisible();
  await check('browse-list');
  const scroll = page.locator('.map-tray-content');
  await scroll.evaluate(el => { el.scrollTop = 200; });
  await expect.poll(() => scroll.evaluate(el => el.scrollTop)).toBeGreaterThan(0);
  await scroll.evaluate(el => { el.scrollTop = 0; });
  const card = page.locator('[data-suggestion-id="1"]');
  await card.focus(); await card.press('Enter');
  await expect(page.getByRole('region', { name: 'Idea details', exact: true })).toHaveAttribute('aria-busy', 'false');
  await check('details');
  await page.locator('summary').filter({ hasText: 'Photos (2)' }).click();
  await page.getByRole('button', { name: 'Open photo 1: Crossing photo 1' }).click();
  await expect(page.getByAltText('Full size')).toBeVisible();
  await check('photo-preview');
  await page.getByRole('button', { name: 'Close photo preview' }).click();
  await page.getByRole('button', { name: 'Open photo 2: Crossing photo 2' }).click();
  await check('photo-second');
  await page.getByRole('button', { name: 'Close photo preview' }).click();
  await page.goBack();
  await expect(card).toBeFocused();
  await page.goForward();
  await expect(page.getByRole('region', { name: 'Idea details', exact: true })).toHaveAttribute('aria-busy', 'false');
  await page.goBack();
  await page.getByRole('textbox', { name: 'Search address or neighborhood' }).fill('Main');
  await expect(page.getByRole('button', { name: 'Searched address, Dallas, TX' })).toBeVisible();
  await check('search-results');
  await page.getByRole('button', { name: 'Searched address, Dallas, TX' }).click();
  await page.getByRole('button', { name: 'Menu', exact: true }).click();
  await check('settings-menu');
  await page.getByRole('link', { name: 'Map settings', exact: true }).click();
  await expect(page.getByRole('dialog', { name: 'Map settings' })).toBeVisible();
  await check('marker-settings');
  const size = page.viewportSize();
  await page.setViewportSize({ width: size.height, height: size.width });
  const settings = page.getByRole('dialog', { name: 'Map settings', exact: true });
  const threshold = page.getByRole('slider', { name: 'Marker threshold zoom level' });
  const settingsBox = await settings.boundingBox();
  const thresholdBox = await threshold.boundingBox();
  expect.soft(thresholdBox.y + thresholdBox.height, 'first settings control fits without scrolling').toBeLessThan(settingsBox.y + settingsBox.height);
  await settings.locator('.floating-modal__content').evaluate(el => { el.scrollTop = el.scrollHeight; });
  await expect(page.getByRole('dialog', { name: 'Map settings', exact: true }).getByRole('button', { name: 'Close', exact: true })).toBeInViewport();
  await settings.locator('.floating-modal__content').evaluate(el => { el.scrollTop = 0; });
  await check('marker-settings-rotated');
  await page.getByRole('dialog', { name: 'Map settings', exact: true }).getByRole('button', { name: 'Close', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Menu', exact: true })).toBeFocused();
  await page.setViewportSize(size);
  await page.getByRole('button', { name: 'Menu', exact: true }).click();
  await page.getByRole('link', { name: 'Map settings', exact: true }).click();
  await page.getByRole('button', { name: 'Rail', exact: true }).click();
  await check('rail-settings');
  await page.getByRole('dialog', { name: 'Map settings', exact: true }).getByRole('button', { name: 'Close', exact: true }).click();
  await page.getByRole('button', { name: 'Menu', exact: true }).click();
  const theme = info.project.use.colorScheme === 'dark' ? 'Light' : 'Dark';
  await page.getByRole('menuitemcheckbox', { name: 'Dark mode' }).click();
  await expect(page.locator('html')).toHaveClass(new RegExp(theme.toLowerCase()));
  await check('theme-switched');
});

